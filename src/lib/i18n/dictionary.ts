export function translate(key: string, params?: Record<string, string | number>): string {
  let s = messages[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      s = s.replaceAll(`{${k}}`, String(v));
    }
  }
  return s;
}
